'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const content = fs.readFileSync(path.join(root, 'install/content.js'), 'utf8');
const sidepanel = fs.readFileSync(path.join(root, 'install/sidepanel.js'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'install/manifest.json'), 'utf8'));
assert.ok(manifest.version.localeCompare('0.10.4') >= 0, '版本应不低于 0.10.4');
assert.ok(content.includes("document.querySelectorAll('input[type=\\\"file\\\"]')"), 'must read native file input FileLists independently from visible text');
assert.ok(content.includes('inputFileEvidenceByName[name]'), 'native file input evidence must participate in matching');
assert.ok(content.includes('baselineNativeSignatures.has'), 'must reject stale pre-existing FileList entries');
assert.ok(content.includes("source:'native-file-input-filelist'"), 'diagnostics must identify native FileList evidence');
assert.ok(content.includes('nativeFileInputState:'), 'diagnostics must show current file input state');
assert.ok(sidepanel.includes('inputFileEvidenceByName:verification?.inputFileEvidenceByName'), 'fallback diagnostic must include FileList evidence');
assert.ok(sidepanel.includes('__inputFileSignatures: baseline.inputFileSignatures'), 'baseline FileList signatures must be carried to verification');
const norm = value => String(value || '').replace(/[（]/g, '(').replace(/[）]/g, ')').replace(/\s+/g, ' ').trim().toLocaleLowerCase();
const escapeRegex = value => String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const filenamePattern = name => {
  const key = norm(name), dot = key.lastIndexOf('.');
  const suffix = '(?:\\(\\s*(?:\\d{8}\\s+\\d{6}|\\d+)\\s*\\))?';
  const body = dot > 0 ? `${escapeRegex(key.slice(0,dot))}\\s*${suffix}\\s*${escapeRegex(key.slice(dot))}${suffix}` : `${escapeRegex(key)}${suffix}`;
  return new RegExp(`(?:^|[^a-z0-9._-])${body}(?=$|[^a-z0-9._-])`, 'i');
};
const sig = f => `${norm(f.name)}|${f.size}|${f.type}`;
const baseline = new Set([]);
const current = {name:'A题（20261019 044718）.pdf',size:553369,type:'application/pdf'};
assert.ok(filenamePattern('A题.pdf').test(norm(current.name)), 'must match timestamp aliases in FileList names');
assert.equal(baseline.has(sig(current)), false, 'new file signature should count as new evidence');
const staleBaseline = new Set([sig(current)]);
assert.equal(staleBaseline.has(sig(current)), true, 'same pre-existing FileList signature must not count as newly attached');
for (const f of ['附件1.xlsx','附件2.xlsx']) assert.ok(filenamePattern(f).test(norm(f)), `must match ${f}`);
console.log('v0.10.2 attachment evidence tests passed: native FileList channel, baseline signature rejection, timestamp alias and XLSX matching.');
